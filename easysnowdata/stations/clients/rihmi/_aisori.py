"""
clients/rihmi/_aisori.py
========================
Scripted export from Web АИСОРИ-М (http://aisori-m.meteo.ru/waisori/), the
RIHMI-WDC portal behind a free login.

The site is a Jakarta Faces / PrimeFaces application with no API. This module
replays the same form posts its pages make (worked out from one recorded
browser session on 2026-10-14), with plain ``requests``:

1. open ``index.xhtml?idata=6`` and follow «Переход на страницу авторизации»
   (a PrimeFaces AJAX command link);
2. post the login form (``…:usr`` / ``…:pwd``);
3. «Выбор данных» → the station-selection page;
4. AJAX ``valueChange`` on «Раздел БД» (``Сутки``) and «источник данных»
   (``SNMAR …`` or ``SNOW …``), then tick the stations and press «>»;
5. «Дальше» → the query page: delimiter, year range, «Все» (every
   parameter), «Результат»;
6. poll the "wait for the query" dialog until «Получить результат» is
   enabled, press it, and on the result page press «Загрузить» for the zip.

Component ids such as ``j_idt59:butres1`` are generated by the server, so
every control is found by its label, field type or position in the page
rather than by a hard-coded id. Each form post carries the page's current
``jakarta.faces.ViewState``, and AJAX responses that update it are applied.

Nothing here is documented by RIHMI; if the site changes, the error says
which step failed.
"""

from __future__ import annotations

import logging
import re
import time
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from typing import Any
from urllib.parse import urljoin

import requests

logger = logging.getLogger(__name__)

BASE_URL = "http://aisori-m.meteo.ru"
_ENTRY = "/waisori/index.xhtml?idata=6"

#: «источник данных» option prefix per dataset.
DATASET_SOURCES = {"route_survey": "SNMAR", "snow_cover": "SNOW"}
_DB_SECTION = "Сутки"
_VIEWSTATE = "jakarta.faces.ViewState"


class AisoriExportError(RuntimeError):
    """A step of the scripted АИСОРИ-М export failed."""


@dataclass
class _Form:
    """One ``<form>``: its id, action and the fields a submit would send."""

    id: str
    action: str
    fields: list[tuple[str, str]] = field(default_factory=list)
    buttons: dict[str, str] = field(default_factory=dict)  # label → name
    links: dict[str, str] = field(default_factory=dict)  # label → id
    names: set[str] = field(default_factory=set)  # every named control


def _forms(html: str, url: str) -> dict[str, _Form]:
    from bs4 import BeautifulSoup  # noqa: PLC0415

    soup = BeautifulSoup(html, "html.parser")
    out: dict[str, _Form] = {}
    for f in soup.find_all("form"):
        fid = f.get("id") or f.get("name") or ""
        form = _Form(fid, urljoin(url, f.get("action") or url))
        form.names = {el["name"] for el in f.find_all(attrs={"name": True})}
        for inp in f.find_all("input"):
            name = inp.get("name")
            if not name:
                continue
            kind = (inp.get("type") or "text").lower()
            if kind in ("checkbox", "radio"):
                if inp.has_attr("checked"):
                    form.fields.append((name, inp.get("value", "on")))
            elif kind not in ("submit", "button", "image"):
                form.fields.append((name, inp.get("value", "")))
        for sel in f.find_all("select"):
            name = sel.get("name")
            if not name:
                continue
            opts = sel.find_all("option")
            chosen = [o for o in opts if o.has_attr("selected")]
            if not chosen and opts and not sel.has_attr("multiple"):
                chosen = opts[:1]  # what a browser submits for a single select
            for opt in chosen:
                form.fields.append((name, opt.get("value", opt.text)))
        for btn in f.find_all("button"):
            if btn.get("name"):
                form.buttons[btn.get_text(" ", strip=True)] = btn["name"]
        for a in f.find_all("a"):
            if a.get("id"):
                form.links[a.get_text(" ", strip=True)] = a["id"]
        out[fid] = form
    return out


def _find(
    forms: dict[str, _Form], label: str, kind: str = "buttons", exact: bool = False
) -> tuple[_Form, str]:
    for form in forms.values():
        for text, name in getattr(form, kind).items():
            if text == label or (not exact and text.startswith(label)):
                return form, name
    raise AisoriExportError(f"АИСОРИ-М page has no control labelled {label!r}")


class AisoriSession:
    """One logged-in Web АИСОРИ-М session.

    Parameters
    ----------
    username, password : str
        The free АИСОРИ-М account.
    session : requests.Session, optional
        Session to use (a fresh one by default).
    base_url : str
        Site root.
    timeout : int
        Per-request timeout in seconds.
    """

    def __init__(
        self,
        username: str,
        password: str,
        *,
        session: requests.Session | None = None,
        base_url: str = BASE_URL,
        timeout: int = 120,
    ) -> None:
        self.username = username
        self._password = password
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self.http = session or requests.Session()
        self.http.headers.setdefault("User-Agent", "easysnowdata")
        self._viewstate = ""
        self._logged_in = False
        self._exported = False

    # ── HTTP plumbing ────────────────────────────────────────────────────────

    def _get(self, url: str) -> requests.Response:
        resp = self.http.get(url, timeout=self.timeout)
        if not resp.ok:
            raise AisoriExportError(f"HTTP {resp.status_code} from {url}")
        resp.encoding = resp.encoding or "utf-8"
        return resp

    def _post(self, url: str, data: list[tuple[str, str]], ajax: bool = False):
        data = [(k, v) for k, v in data if k != _VIEWSTATE]
        data.append((_VIEWSTATE, self._viewstate))
        headers = {"Faces-Request": "partial/ajax"} if ajax else {}
        resp = self.http.post(url, data=data, headers=headers, timeout=self.timeout)
        if not resp.ok:
            raise AisoriExportError(f"HTTP {resp.status_code} from {url}")
        if ajax:
            self._apply_partial(resp.text)
        return resp

    def _page(self, resp: requests.Response) -> dict[str, _Form]:
        resp.encoding = "utf-8"
        forms = _forms(resp.text, resp.url)
        for form in forms.values():
            for k, v in form.fields:
                if k == _VIEWSTATE:
                    self._viewstate = v
        return forms

    def _apply_partial(self, xml: str) -> dict[str, str]:
        """Apply a PrimeFaces partial response; return ``{id: CDATA}``."""
        updates: dict[str, str] = {}
        try:
            root = ET.fromstring(xml)
        except ET.ParseError:
            return updates
        for up in root.iter("update"):
            uid = up.get("id", "")
            updates[uid] = up.text or ""
            if _VIEWSTATE in uid:
                self._viewstate = (up.text or "").strip()
        for err in root.iter("error"):
            raise AisoriExportError(
                "АИСОРИ-М returned an error: " + " ".join(err.itertext())[:300]
            )
        redirect = root.find(".//redirect")
        if redirect is not None:
            updates["__redirect__"] = redirect.get("url", "")
        return updates

    def _ajax(
        self,
        form: _Form,
        source: str,
        *,
        execute: str = "@all",
        render: str | None = None,
        event: str | None = None,
        extra: list[tuple[str, str]] | None = None,
        fields: list[tuple[str, str]] | None = None,
    ) -> dict[str, str]:
        data = [
            ("jakarta.faces.partial.ajax", "true"),
            ("jakarta.faces.source", source),
            ("jakarta.faces.partial.execute", execute),
        ]
        if render:
            data.append(("jakarta.faces.partial.render", render))
        if event:
            data += [
                ("jakarta.faces.behavior.event", event),
                ("jakarta.faces.partial.event", "change"),
            ]
        else:
            data.append((source, source))
        data.append((form.id, form.id))
        data += [
            (k, v)
            for k, v in (fields if fields is not None else form.fields)
            if k != form.id
        ]
        data += extra or []
        resp = self._post(form.action, data, ajax=True)
        return self._apply_partial(resp.text)

    # ── Steps ────────────────────────────────────────────────────────────────

    def login(self) -> None:
        """Log in (once per session)."""
        if self._logged_in:
            return
        forms = self._page(self._get(self.base_url + _ENTRY))
        form, link = _find(forms, "Переход на страницу авторизации", "links")
        self._ajax(form, link)
        forms = self._page(self._get(urljoin(form.action, "index0.xhtml")))
        login = next(
            (f for f in forms.values() if any(k.endswith(":pwd") for k, _ in f.fields)),
            None,
        )
        if login is None:
            raise AisoriExportError("АИСОРИ-М login form not found")
        fields = []
        for k, v in login.fields:
            if k.endswith(":usr"):
                v = self.username
            elif k.endswith(":pwd"):
                v = self._password
            fields.append((k, v))
        ok = login.buttons.get("OK")
        if ok is None:
            raise AisoriExportError("АИСОРИ-М login form has no OK button")
        fields = [(k, v) for k, v in fields if k != login.id]
        resp = self._post(login.action, [(login.id, login.id), *fields, (ok, "")])
        if "index1" not in resp.url:
            raise AisoriExportError(
                "АИСОРИ-М login failed — check AISORI_USERNAME / AISORI_PASSWORD"
            )
        self._page(resp)
        self._logged_in = True
        self._home = resp

    def export(
        self,
        dataset: str,
        station_ids: list[str],
        first_year: int,
        last_year: int,
        *,
        delimiter: str = ";",
        poll_seconds: float = 2.0,
        max_wait: float = 600.0,
    ) -> bytes:
        """Run one export and return the zip АИСОРИ-М serves.

        Parameters
        ----------
        dataset : {"route_survey", "snow_cover"}
            ``SNMAR`` route surveys or ``SNOW`` daily snow cover.
        station_ids : list[str]
            WMO indexes. Those the source does not offer are skipped (with a
            warning); none at all raises.
        first_year, last_year : int
            Inclusive year range.
        delimiter : {";", " "}
            ``;`` (default) or the fixed-width space variant.
        poll_seconds, max_wait : float
            How often, and for how long, to wait for the query to finish.

        Returns
        -------
        bytes
            The zip (``wr*.txt``, ``fld*.txt``, ``statlist*.txt``).

        Raises
        ------
        AisoriExportError
            On any failed step.
        """
        if dataset not in DATASET_SOURCES:
            raise AisoriExportError(f"Unknown АИСОРИ-М dataset {dataset!r}")
        if self._exported:
            # The site's pages are stateful: after a download the session sits
            # on the result page, so each export starts from a fresh login.
            headers = dict(self.http.headers)
            self.http = requests.Session()
            self.http.headers.update(headers)
            self._logged_in = False
        self.login()
        forms = self._page(self._home)
        form, btn = _find(forms, "Выбор данных")
        forms = self._page(self._post(form.action, [(form.id, form.id), (btn, "")]))

        # Station selection page: section, source, stations.
        sel = next((f for f in forms.values() if f"{f.id}:razbd" in f.names), None)
        if sel is None:
            raise AisoriExportError("АИСОРИ-М station-selection form not found")
        razbd = f"{sel.id}:razbd"
        istd = f"{sel.id}:istd"
        base = [(k, v) for k, v in sel.fields if k not in (razbd, istd, sel.id)]
        _, move_btn = _find({sel.id: sel}, ">", exact=True)
        _, next_btn = _find({sel.id: sel}, "Дальше")
        ups = self._ajax(
            sel,
            razbd,
            execute=razbd,
            render=f"{istd} {sel.id}:hlist1 {sel.id}:hlist2",
            event="valueChange",
            fields=[*base, (razbd, _DB_SECTION), (istd, "")],
        )
        source = _option_starting(ups.get(istd, ""), DATASET_SOURCES[dataset])
        if source is None:
            raise AisoriExportError(
                f"АИСОРИ-М offers no {DATASET_SOURCES[dataset]} source under {_DB_SECTION}"
            )
        ups = self._ajax(
            sel,
            istd,
            execute=istd,
            render=f"{sel.id}:hlist1 {sel.id}:hlist2",
            event="valueChange",
            fields=[*base, (razbd, _DB_SECTION), (istd, source)],
        )
        offered = _options(ups.get(f"{sel.id}:hlist1", ""))
        by_index = {o.split()[0]: o for o in offered if o.split()}
        wanted = [by_index[s] for s in station_ids if s in by_index]
        missing = [s for s in station_ids if s not in by_index]
        if missing:
            logger.warning(
                "АИСОРИ-М %s: stations not offered and skipped: %s",
                DATASET_SOURCES[dataset],
                ", ".join(missing),
            )
        if not wanted:
            raise AisoriExportError(
                f"None of {station_ids} is offered by АИСОРИ-М "
                f"{DATASET_SOURCES[dataset]} ({len(offered)} stations are)"
            )
        moved = [(f"{sel.id}:hlist1_input", o) for o in wanted]
        self._ajax(
            sel,
            move_btn,
            render=f"{sel.id}:hlist1 {sel.id}:hlist2",
            fields=[*base, (razbd, _DB_SECTION), (istd, source), *moved],
        )
        resp = self._post(
            sel.action,
            [
                (sel.id, sel.id),
                (razbd, _DB_SECTION),
                (istd, source),
                (next_btn, ""),
                (f"{sel.id}:hlist1_filter", ""),
            ],
        )
        forms = self._page(resp)

        # Query page: delimiter, years, every parameter, run.
        query = next(
            (
                f
                for f in forms.values()
                if any(k.endswith(":seldelim") for k, _ in f.fields)
            ),
            None,
        )
        if query is None:
            raise AisoriExportError("АИСОРИ-М query page not found after «Дальше»")
        ranges = [k for k, _ in query.fields if re.search(r":\d+:j_idt\d+$", k)]
        if len(ranges) < 2:
            raise AisoriExportError("АИСОРИ-М query page has no year range fields")
        delim = "1" if delimiter == ";" else "0"

        def query_fields(years: bool) -> list[tuple[str, str]]:
            out = []
            for k, v in query.fields:
                if k.endswith(":seldelim"):
                    v = delim
                elif k == ranges[0]:
                    v = str(first_year) if years else ""
                elif k == ranges[1]:
                    v = str(last_year) if years else ""
                out.append((k, v))
            return out

        _, all_btn = _find({query.id: query}, "Все", exact=True)
        self._ajax(
            query,
            all_btn,
            render=f"{query.id}:flist2",
            fields=query_fields(False),
        )
        _, run_btn = _find({query.id: query}, "Результат", exact=True)
        self._ajax(query, run_btn, fields=query_fields(True))

        # Wait for the query: the dialog's poll re-renders its two buttons.
        dialog, get_btn = _find(forms, "Получить результат")
        poll = f"{dialog.id}:poll"
        close_btn = dialog.buttons.get("Закрыть", f"{dialog.id}:but1close")
        deadline = time.monotonic() + max_wait
        while True:
            ups = self._ajax(
                dialog,
                poll,
                render=f"{close_btn} {get_btn}",
                fields=[],
            )
            html = ups.get(get_btn, "")
            if html and "disabled" not in html:
                break
            closed = ups.get(close_btn, "")
            if closed and "disabled" not in closed and html:
                raise AisoriExportError("АИСОРИ-М reported an error running the query")
            if time.monotonic() > deadline:
                raise AisoriExportError("АИСОРИ-М query did not finish in time")
            time.sleep(poll_seconds)
        self._ajax(dialog, get_btn, fields=[])

        result = self._get(urljoin(dialog.action, "result.xhtml"))
        forms = self._page(result)
        rform, load_btn = _find(forms, "Загрузить")
        resp = self._post(
            rform.action,
            [
                (rform.id, rform.id),
                *[(k, v) for k, v in rform.fields if k != rform.id],
                (load_btn, ""),
            ],
        )
        if not resp.content.startswith(b"PK"):
            raise AisoriExportError("АИСОРИ-М «Загрузить» did not return a zip")
        self._exported = True
        return resp.content


def _options(html: str) -> list[str]:
    """Option values of a rendered select, exactly as the server sent them.

    They are posted back verbatim: the server matches them as strings, and
    the snow-cover source pads its labels (``"22113 Мурманск  Россия"``).
    """
    import html as _html  # noqa: PLC0415

    return [
        _html.unescape(v)
        for v in re.findall(r'<option[^>]*\bvalue="([^"]*)"', html)
        if v.strip()
    ]


def _option_starting(html: str, prefix: str) -> str | None:
    for opt in re.findall(r'<option value="([^"]*)"', html):
        if opt.startswith(prefix):
            return opt
    return None


def export_zip(
    username: str,
    password: str,
    dataset: str,
    station_ids: list[str],
    first_year: int,
    last_year: int,
    **kwargs: Any,
) -> bytes:
    """Log in and run one export; see :meth:`AisoriSession.export`."""
    return AisoriSession(username, password).export(
        dataset, station_ids, first_year, last_year, **kwargs
    )
